#!/usr/bin/env node
// Reel Studio - Edit mode, step 2: captioned talking-head reel.
//
//   node engine/build_talking_head.mjs work/take_07 [--cta DEMO] [--id take_07_reel]
//
// Input folder = the output of tools/edit_clip.py (cut.mp4 + words.json).
// Builds a HyperFrames composition in work/<id>/ with:
//   - the cut footage, cropped to 9:16 (object-fit: cover)
//   - kinetic captions, 3 words at a time, word-by-word highlight, kept
//     above the lower safe area (move with --caption-y if they cover the face)
//   - punch-in zooms at sentence starts (alternating 100% / 112%)
//   - optional end card: "Comment <KEYWORD>"
// Then render with:  engine/node_modules/.bin/hyperframes render work/<id> -o exports/<id>.mp4

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { esc } from "./scenes.mjs";

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const inDir = args.find((a) => !a.startsWith("--") && !args[args.indexOf(a) - 1]?.startsWith("--"));
if (!inDir) {
  console.error("usage: node engine/build_talking_head.mjs work/<clip_folder> [--cta KEYWORD] [--id name] [--caption-y 1180]");
  process.exit(2);
}
const src = path.resolve(inDir);
const id = opt("--id", path.basename(src) + "_reel");
const cta = opt("--cta", null);
const capY = Number(opt("--caption-y", 1180));
const brand = JSON.parse(fs.readFileSync(path.join(ROOT, "brand/brand.json"), "utf8"));
const words = JSON.parse(fs.readFileSync(path.join(src, "words.json"), "utf8"));
if (!words.length) {
  console.error("words.json is empty - run tools/edit_clip.py with faster-whisper installed to get captions.");
  process.exit(1);
}

const cutDur = words.at(-1).end + 0.4;
const endCard = cta ? 2.2 : 0;
const total = +(cutDur + endCard).toFixed(3);
const out = path.join(ROOT, "work", id);
fs.mkdirSync(path.join(out, "assets"), { recursive: true });
fs.copyFileSync(path.join(src, "cut.mp4"), path.join(out, "assets", "cut.mp4"));
fs.copyFileSync(require.resolve("gsap/dist/gsap.min.js"), path.join(out, "gsap.min.js"));

// caption groups: 3 words, break early after punctuation
const groups = [];
let cur = [];
words.forEach((w, i) => {
  cur.push({ ...w, i });
  if (cur.length === 3 || /[.,!?;:]$/.test(w.word)) { groups.push(cur); cur = []; }
});
if (cur.length) groups.push(cur);

const c = brand.colors, f = brand.fonts;
const parts = [], js = [];
groups.forEach((g, gi) => {
  const s = g[0].start, e = gi < groups.length - 1 ? groups[gi + 1][0].start : cutDur;
  const longest = g.reduce((a, b) => (b.word.replace(/\W/g, "").length > a.word.replace(/\W/g, "").length ? b : a));
  parts.push(`<div class="clip cap" id="g${gi}" data-start="${s.toFixed(3)}" data-duration="${Math.max(e - s, 0.1).toFixed(3)}" data-track-index="1">${g
    .map((w) => `<span class="w${w === longest ? " em" : ""}" id="w${w.i}">${esc(w.word)}</span>`)
    .join(" ")}</div>`);
  js.push(`tl.from("#g${gi}", {y:30, opacity:0, duration:0.14, ease:"power2.out"}, ${s.toFixed(3)});`);
  g.forEach((w) => js.push(`tl.fromTo("#w${w.i}", {opacity:0.45}, {opacity:1, duration:0.08}, ${w.start.toFixed(3)});`));
});

// punch-ins at sentence starts (after . ! ?), alternating zoom
let zoomIn = true;
words.forEach((w, i) => {
  if (i === 0 || /[.!?]$/.test(words[i - 1].word)) {
    js.push(`tl.to("#footage", {scale:${zoomIn ? 1.12 : 1.0}, duration:0.2, ease:"power2.out"}, ${Math.max(w.start - 0.05, 0).toFixed(3)});`);
    zoomIn = !zoomIn;
  }
});

const end = cta
  ? `<div class="clip endcard" id="endcard" data-start="${cutDur.toFixed(3)}" data-duration="${endCard}" data-track-index="2">
       <div class="small">comment</div><div class="kw">${esc(cta)}</div><div class="logo">${esc(brand.logo_text || "")}</div></div>`
  : "";
if (cta) {
  js.push(`tl.from("#endcard .kw", {scale:0.4, opacity:0, duration:0.35, ease:"back.out(2)"}, ${(cutDur + 0.1).toFixed(3)});`);
  js.push(`tl.fromTo("#endcard .kw", {scale:1}, {scale:1.08, duration:0.4, yoyo:true, repeat:3, ease:"sine.inOut"}, ${(cutDur + 0.5).toFixed(3)});`);
}

const html = `<!doctype html>
<html lang="en" data-resolution="portrait"><head><meta charset="UTF-8" />
<meta name="viewport" content="width=1080, height=1920" />
<!-- GENERATED by engine/build_talking_head.mjs - re-run it instead of editing. -->
<script src="gsap.min.js"></script>
<style>
* { margin:0; padding:0; box-sizing:border-box; }
html, body { width:1080px; height:1920px; overflow:hidden; background:#000; }
#root { position:relative; width:1080px; height:1920px; font-family:${f.display}; }
.clip { position:absolute; }
#footage { left:0; top:0; width:1080px; height:1920px; object-fit:cover; transform-origin:50% 35%; }
.cap { left:80px; right:140px; top:${capY}px; text-align:center; font-weight:800; font-size:72px; line-height:1.15; color:#fff;
       text-shadow:0 4px 18px rgba(0,0,0,.65), 0 0 2px #000; }
.w { display:inline-block; }
.em { color:${c.accent}; font-family:${f.emphasis}; font-style:italic; font-weight:600; }
.endcard { inset:0; background:${c.accent}; display:flex; flex-direction:column; align-items:center; justify-content:center; color:${c.accent_ink}; }
.small { font:500 44px ${f.mono}; margin-bottom:16px; }
.kw { font-weight:900; font-size:220px; background:${c.accent_ink}; color:${c.accent}; padding:10px 50px; border-radius:36px; }
.logo { margin-top:80px; padding:10px 18px; border:3px solid ${c.accent_ink}; border-radius:10px; font:800 30px ${f.display}; }
</style></head><body>
<div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1080" data-height="1920">
<video class="clip" id="footage" src="assets/cut.mp4" data-start="0" data-duration="${cutDur.toFixed(3)}" data-has-audio="true" data-track-index="0"></video>
${parts.join("\n")}
${end}
</div>
<script>
window.__timelines = window.__timelines || {};
const tl = gsap.timeline({ paused: true });
${js.join("\n")}
tl.set({}, {}, ${total});
window.__timelines["main"] = tl;
tl.seek(0);
</script></body></html>
`;
fs.writeFileSync(path.join(out, "index.html"), html);
fs.writeFileSync(path.join(out, "meta.json"), JSON.stringify({ id, name: id }, null, 2));
fs.writeFileSync(path.join(out, "hyperframes.json"), JSON.stringify({ paths: { assets: "assets" } }, null, 2));
console.log(`Built work/${id}/index.html  (${words.length} words, ${groups.length} caption lines, ${total}s)`);
console.log(`Render: engine/node_modules/.bin/hyperframes render work/${id} -o exports/${id}.mp4`);
